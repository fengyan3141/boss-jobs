"""城市名 → BOSS 城市编码（搜索链接里的 city= 参数）。

前 9 个在实际采集中验证过，其余按 BOSS 的同一编码规则补充。
不在表里的城市：在 BOSS 网页上切到该城市，复制地址栏 city= 后面的数字，
写进配置文件 cities 里，如 {西安: "101110100"}。
"""

CITY_CODES = {
    # 实测
    "北京": "101010100",
    "上海": "101020100",
    "广州": "101280100",
    "深圳": "101280600",
    "杭州": "101210100",
    "成都": "101270100",
    "苏州": "101190400",
    "南京": "101190100",
    "武汉": "101200100",
    # 未实测
    "全国": "100010000",
    "天津": "101030100",
    "重庆": "101040100",
    "西安": "101110100",
    "长沙": "101250100",
    "郑州": "101180100",
    "厦门": "101230200",
    "合肥": "101220100",
    "青岛": "101120200",
}


def resolve(cities):
    """配置里的 cities 列表 → [(名字, 编码)]。项可以是「北京」或 {西安: "101110100"}。"""
    out = []
    for item in cities or []:
        if isinstance(item, dict):
            out.extend((str(k), str(v)) for k, v in item.items())
        elif item in CITY_CODES:
            out.append((item, CITY_CODES[item]))
        else:
            raise SystemExit(f"不认识的城市「{item}」，请在配置里写成 {{{item}: 城市编码}}，编码见 cities.py 说明")
    return out
